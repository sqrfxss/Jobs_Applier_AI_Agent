"""Private, one-page PDF export of an already-reviewed academic Word letter.

Uses native Microsoft Word on Windows and LibreOffice elsewhere. Does not
download fonts, invoke an AI model, access a university or submit a form.
"""

from __future__ import annotations

import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from aihawk.academic_motivation import MotivationError


def _word_export(src: Path, dst: Path) -> None:
    try:
        from win32com.client import DispatchEx
    except ImportError as exc:
        raise MotivationError("PDF export on Windows requires pywin32 and Microsoft Word.") from exc
    word: Any = None
    document: Any = None
    try:
        word = DispatchEx("Word.Application")
        word.Visible = False
        word.DisplayAlerts = 0
        word.AutomationSecurity = 3
        document = word.Documents.Open(str(src), ReadOnly=True, AddToRecentFiles=False)
        document.Repaginate()
        if document.ComputeStatistics(2) != 1:
            raise MotivationError("The letter does not fit on one Microsoft Word page.")
        document.ExportAsFixedFormat(str(dst), 17)
    finally:
        if document is not None:
            document.Close(0)
        if word is not None:
            word.Quit(0)


def _libreoffice_export(src: Path, dst: Path) -> None:
    executable = shutil.which("libreoffice") or shutil.which("soffice")
    if not executable:
        raise MotivationError("Install LibreOffice for academic Word-to-PDF conversion on this platform.")
    with tempfile.TemporaryDirectory(prefix="aihawk-lo-profile-", dir=str(src.parent)) as profile:
        cmd = [
            executable,
            "-env:UserInstallation=" + Path(profile).as_uri(),
            "--headless",
            "--convert-to",
            "pdf:writer_pdf_Export",
            "--outdir",
            str(dst.parent),
            str(src),
        ]
        try:
            run = subprocess.run(cmd, capture_output=True, timeout=90, check=False)
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise MotivationError("The office PDF conversion did not finish.") from exc
        expected = dst.parent / (src.stem + ".pdf")
        if run.returncode != 0 or not expected.is_file():
            raise MotivationError("LibreOffice did not produce the required PDF.")
        if expected != dst:
            expected.replace(dst)


def _verify_one_page_pdf(pdf: Path, *, expected_name: str, expected_institution: str) -> None:
    try:
        from pypdf import PdfReader
    except ImportError as exc:
        raise MotivationError("Install pypdf to validate academic PDF output.") from exc
    try:
        reader = PdfReader(str(pdf))
        if len(reader.pages) != 1:
            raise MotivationError("Motivation letter PDF must be exactly one page.")
        page = reader.pages[0]
        width = float(page.mediabox.width)
        height = float(page.mediabox.height)
        if abs(width - 595.3) > 3 or abs(height - 841.9) > 3:
            raise MotivationError("Motivation letter PDF must be A4.")
        text = page.extract_text() or ""
        for text_required in ("MOTIVATION LETTER", expected_name, expected_institution):
            if text_required not in text:
                raise MotivationError("PDF lost a required motivation-letter heading or signature.")
        if any(term in text.casefold() for term in ("generated by chatgpt", "as an ai language model", "watermark")):
            raise MotivationError("PDF contains unexpected generated-text branding.")
        resources = page.get("/Resources")
        fonts = resources.get_object().get("/Font", {}) if resources else {}
        names = [str(entry.get_object().get("/BaseFont", "")) for entry in fonts.get_object().values()] if fonts else []
        if not any("timesnewroman" in value.replace(" ", "").casefold() for value in names):
            raise MotivationError("PDF does not report Times New Roman font resources.")
    except MotivationError:
        raise
    except Exception as exc:
        raise MotivationError("Unable to validate the generated academic PDF.") from exc


def export_letter_pdf(source: Path, destination: Path, *, expected_name: str, expected_institution: str) -> Path:
    """Export in private application folder; refuse overwrites and unverified PDFs."""
    source = source.resolve(strict=True)
    destination = destination.resolve()
    if source.suffix.casefold() != ".docx" or destination.suffix.casefold() != ".pdf":
        raise MotivationError("Source must be DOCX and destination PDF.")
    if source.parent != destination.parent:
        raise MotivationError("PDF must remain beside its private DOCX source.")
    if any((folder / ".git").exists() for folder in (source.parent, *source.parent.parents)):
        raise MotivationError("Private applicant documents cannot be exported in a source repository.")
    if destination.exists():
        raise MotivationError("PDF already exists; refusing to overwrite a reviewed file.")
    from docx import Document

    original = Document(str(source))
    text = "\n".join(paragraph.text for paragraph in original.paragraphs)
    if not all(marker in text for marker in ("MOTIVATION LETTER", expected_name, expected_institution)):
        raise MotivationError("Word source does not contain this applicant and institution.")
    if len(original.sections) != 1:
        raise MotivationError("Academic letter has more than one Word section.")
    from aihawk.academic_document_gate import require_writing_preflight

    try:
        require_writing_preflight(source)
    except ValueError as exc:
        raise MotivationError("Refusing PDF export from noncompliant Word file: " + str(exc)) from exc
    with tempfile.TemporaryDirectory(prefix=".aihawk-pdf-", dir=str(source.parent)) as private_tmp:
        temporary = Path(private_tmp) / (source.stem + ".pdf")
        if sys.platform == "win32":
            _word_export(source, temporary)
        else:
            _libreoffice_export(source, temporary)
        if not temporary.is_file():
            raise MotivationError("No PDF output was produced.")
        _verify_one_page_pdf(temporary, expected_name=expected_name, expected_institution=expected_institution)
        try:
            require_writing_preflight(temporary, source_docx=source)
        except ValueError as exc:
            raise MotivationError("Refusing PDF export with footer or broken justification: " + str(exc)) from exc
        os.replace(temporary, destination)
    # No PDF is submitted or uploaded by this function.
    return destination


def file_digest(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(262144), b""):
            digest.update(chunk)
    return digest.hexdigest()
